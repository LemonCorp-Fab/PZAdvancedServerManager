    public static void GenerateStandalone(string modsRoot, PackageProject project)
    {
        var root = Path.Combine(modsRoot, project.ControlModId);
        NoticeModGenerator.WriteManifest(root, project.ControlModId, $"{project.Name} — control", "In-game pack status and administrator console generated by PZ Advanced Server Manager.");
        WriteFiles(root, project);
    }

    public static void InjectIntoFusion(string fusionRoot, PackageProject project) => WriteFiles(fusionRoot, project);

    private static void WriteFiles(string root, PackageProject project)
    {
        var clientPath = Path.Combine(root, "common", "media", "lua", "client", "PZASM_ControlClient.lua");
        var serverPath = Path.Combine(root, "common", "media", "lua", "server", "PZASM_ControlServer.lua");
        Directory.CreateDirectory(Path.GetDirectoryName(clientPath)!);
        Directory.CreateDirectory(Path.GetDirectoryName(serverPath)!);
        File.WriteAllText(clientPath, CreateClient(project), new UTF8Encoding(false));
        File.WriteAllText(serverPath, CreateServer(project), new UTF8Encoding(false));
    }

